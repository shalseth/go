#include "textflag.h"

// The T4 AES instructions compute half a round each: AESEROUND01 gives
// columns 0-1 of the next state and AESEROUND23 columns 2-3, both from
// the whole state in two double registers. Round keys are the standard
// FIPS 197 schedule, in the byte order a load gives on this big-endian
// machine. Decryption uses the same schedule backwards: AESDROUND adds
// the round key before InvMixColumns.

// func encryptBlockAsm(nr int, xk *uint32, dst, src *byte)
// dst and src are 8-aligned.
TEXT ·encryptBlockAsm(SB), NOSPLIT|NOFRAME, $0-32
	MOVD	nr+0(FP), R8
	MOVD	xk+8(FP), R9
	MOVD	dst+16(FP), R10
	MOVD	src+24(FP), R11
	MOVD	(R11), R12
	MOVD	8(R11), R13
	MOVD	(R9), R16
	MOVD	8(R9), R17
	XOR	R16, R12
	XOR	R17, R13
	MOVXTOD	R12, D2
	MOVXTOD	R13, D4
	ADD	$16, R9
	SUB	$1, R8

encround:
	FMOVD	(R9), D6
	FMOVD	8(R9), D8
	AESEROUND01	D6, D2, D4, D10
	AESEROUND23	D8, D2, D4, D4
	FMOVD	D10, D2
	ADD	$16, R9
	SUB	$1, R8
	BRNZ	R8, encround

	FMOVD	(R9), D6
	FMOVD	8(R9), D8
	AESEROUND01L	D6, D2, D4, D10
	AESEROUND23L	D8, D2, D4, D4
	FMOVD	D10, (R10)
	FMOVD	D4, 8(R10)
	RET

// func decryptBlockAsm(nr int, xk *uint32, dst, src *byte)
// xk is the encryption schedule. dst and src are 8-aligned.
TEXT ·decryptBlockAsm(SB), NOSPLIT|NOFRAME, $0-32
	MOVD	nr+0(FP), R8
	MOVD	xk+8(FP), R9
	MOVD	dst+16(FP), R10
	MOVD	src+24(FP), R11
	SLLD	$4, R8, R16
	ADD	R16, R9
	MOVD	(R11), R12
	MOVD	8(R11), R13
	MOVD	(R9), R16
	MOVD	8(R9), R17
	XOR	R16, R12
	XOR	R17, R13
	MOVXTOD	R12, D2
	MOVXTOD	R13, D4
	SUB	$16, R9
	SUB	$1, R8

decround:
	FMOVD	(R9), D6
	FMOVD	8(R9), D8
	AESDROUND01	D6, D2, D4, D10
	AESDROUND23	D8, D2, D4, D4
	FMOVD	D10, D2
	SUB	$16, R9
	SUB	$1, R8
	BRNZ	R8, decround

	FMOVD	(R9), D6
	FMOVD	8(R9), D8
	AESDROUND01L	D6, D2, D4, D10
	AESDROUND23L	D8, D2, D4, D4
	FMOVD	D10, (R10)
	FMOVD	D4, 8(R10)
	RET

// func expandKeyAsm(nr int, key *byte, enc *uint32)
// key is 8-aligned. Only the encryption schedule is written.
TEXT ·expandKeyAsm(SB), NOSPLIT|NOFRAME, $0-24
	MOVD	nr+0(FP), R8
	MOVD	key+8(FP), R9
	MOVD	enc+16(FP), R10
	CMP	$10, R8
	BED	ks128
	CMP	$12, R8
	BED	ks192
	FMOVD	(R9), D2
	FMOVD	8(R9), D4
	FMOVD	16(R9), D6
	FMOVD	24(R9), D8
	FMOVD	D2, (R10)
	FMOVD	D4, 8(R10)
	FMOVD	D6, 16(R10)
	FMOVD	D8, 24(R10)
	AESKEXPAND1	D2, D8, $0, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND0	D4, D6, D6
	AESKEXPAND2	D6, D8, D8
	FMOVD	D2, 32(R10)
	FMOVD	D4, 40(R10)
	FMOVD	D6, 48(R10)
	FMOVD	D8, 56(R10)
	AESKEXPAND1	D2, D8, $1, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND0	D4, D6, D6
	AESKEXPAND2	D6, D8, D8
	FMOVD	D2, 64(R10)
	FMOVD	D4, 72(R10)
	FMOVD	D6, 80(R10)
	FMOVD	D8, 88(R10)
	AESKEXPAND1	D2, D8, $2, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND0	D4, D6, D6
	AESKEXPAND2	D6, D8, D8
	FMOVD	D2, 96(R10)
	FMOVD	D4, 104(R10)
	FMOVD	D6, 112(R10)
	FMOVD	D8, 120(R10)
	AESKEXPAND1	D2, D8, $3, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND0	D4, D6, D6
	AESKEXPAND2	D6, D8, D8
	FMOVD	D2, 128(R10)
	FMOVD	D4, 136(R10)
	FMOVD	D6, 144(R10)
	FMOVD	D8, 152(R10)
	AESKEXPAND1	D2, D8, $4, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND0	D4, D6, D6
	AESKEXPAND2	D6, D8, D8
	FMOVD	D2, 160(R10)
	FMOVD	D4, 168(R10)
	FMOVD	D6, 176(R10)
	FMOVD	D8, 184(R10)
	AESKEXPAND1	D2, D8, $5, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND0	D4, D6, D6
	AESKEXPAND2	D6, D8, D8
	FMOVD	D2, 192(R10)
	FMOVD	D4, 200(R10)
	FMOVD	D6, 208(R10)
	FMOVD	D8, 216(R10)
	AESKEXPAND1	D2, D8, $6, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 224(R10)
	FMOVD	D4, 232(R10)
	RET

ks128:
	FMOVD	(R9), D2
	FMOVD	8(R9), D4
	FMOVD	D2, (R10)
	FMOVD	D4, 8(R10)
	AESKEXPAND1	D2, D4, $0, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 16(R10)
	FMOVD	D4, 24(R10)
	AESKEXPAND1	D2, D4, $1, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 32(R10)
	FMOVD	D4, 40(R10)
	AESKEXPAND1	D2, D4, $2, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 48(R10)
	FMOVD	D4, 56(R10)
	AESKEXPAND1	D2, D4, $3, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 64(R10)
	FMOVD	D4, 72(R10)
	AESKEXPAND1	D2, D4, $4, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 80(R10)
	FMOVD	D4, 88(R10)
	AESKEXPAND1	D2, D4, $5, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 96(R10)
	FMOVD	D4, 104(R10)
	AESKEXPAND1	D2, D4, $6, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 112(R10)
	FMOVD	D4, 120(R10)
	AESKEXPAND1	D2, D4, $7, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 128(R10)
	FMOVD	D4, 136(R10)
	AESKEXPAND1	D2, D4, $8, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 144(R10)
	FMOVD	D4, 152(R10)
	AESKEXPAND1	D2, D4, $9, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 160(R10)
	FMOVD	D4, 168(R10)
	RET

ks192:
	FMOVD	(R9), D2
	FMOVD	8(R9), D4
	FMOVD	16(R9), D6
	FMOVD	D2, (R10)
	FMOVD	D4, 8(R10)
	FMOVD	D6, 16(R10)
	AESKEXPAND1	D2, D6, $0, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND2	D4, D6, D6
	FMOVD	D2, 24(R10)
	FMOVD	D4, 32(R10)
	FMOVD	D6, 40(R10)
	AESKEXPAND1	D2, D6, $1, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND2	D4, D6, D6
	FMOVD	D2, 48(R10)
	FMOVD	D4, 56(R10)
	FMOVD	D6, 64(R10)
	AESKEXPAND1	D2, D6, $2, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND2	D4, D6, D6
	FMOVD	D2, 72(R10)
	FMOVD	D4, 80(R10)
	FMOVD	D6, 88(R10)
	AESKEXPAND1	D2, D6, $3, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND2	D4, D6, D6
	FMOVD	D2, 96(R10)
	FMOVD	D4, 104(R10)
	FMOVD	D6, 112(R10)
	AESKEXPAND1	D2, D6, $4, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND2	D4, D6, D6
	FMOVD	D2, 120(R10)
	FMOVD	D4, 128(R10)
	FMOVD	D6, 136(R10)
	AESKEXPAND1	D2, D6, $5, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND2	D4, D6, D6
	FMOVD	D2, 144(R10)
	FMOVD	D4, 152(R10)
	FMOVD	D6, 160(R10)
	AESKEXPAND1	D2, D6, $6, D2
	AESKEXPAND2	D2, D4, D4
	AESKEXPAND2	D4, D6, D6
	FMOVD	D2, 168(R10)
	FMOVD	D4, 176(R10)
	FMOVD	D6, 184(R10)
	AESKEXPAND1	D2, D6, $7, D2
	AESKEXPAND2	D2, D4, D4
	FMOVD	D2, 192(R10)
	FMOVD	D4, 200(R10)
	RET
