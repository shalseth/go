// func gcmGhashBlocks(h, y *[2]uint64, p *byte, n int)
//
// Folds n 16-byte blocks at p into y: y = (y ^ x) * h in GF(2^128). A
// load gives each block as two big-endian 64-bit halves, which is the
// representation the generic code builds by hand. The 128-bit product
// is Karatsuba over the halves, with the VIS3 carry-less XMULX and
// XMULXHI, then shifted left one bit and reduced as in ghash.go. p is
// 8-aligned.
TEXT ·gcmGhashBlocks(SB), NOSPLIT|NOFRAME, $0-32
	MOVD	h+0(FP), R8
	MOVD	y+8(FP), R9
	MOVD	p+16(FP), R10
	MOVD	n+24(FP), R11
	MOVD	(R8), R16
	MOVD	8(R8), R17
	XOR	R16, R17, R18
	MOVD	(R9), R12
	MOVD	8(R9), R13

ghashloop:
	BRZ	R11, ghashdone
	MOVD	(R10), R1
	MOVD	8(R10), R2
	XOR	R1, R12
	XOR	R2, R13

	// lo*lo, hi*hi and (hi^lo)*(hi^lo).
	XMULX	R13, R17, R3
	XMULXHI	R13, R17, R4
	XMULX	R12, R16, R5
	XMULXHI	R12, R16, R19
	XOR	R12, R13, R20
	XMULX	R20, R18, R24
	XMULXHI	R20, R18, R25
	XOR	R3, R24
	XOR	R5, R24
	XOR	R4, R25
	XOR	R19, R25
	XOR	R24, R4
	XOR	R25, R5

	// The 256-bit product is R19:R5:R4:R3. Shift it left one bit.
	SRLD	$63, R5, R1
	SLLD	$1, R19, R19
	OR	R1, R19
	SRLD	$63, R4, R1
	SLLD	$1, R5, R5
	OR	R1, R5
	SRLD	$63, R3, R1
	SLLD	$1, R4, R4
	OR	R1, R4
	SLLD	$1, R3, R3

	// Reduce R3 into R5:R4, then R4 into R19:R5.
	SRLD	$1, R3, R1
	XOR	R3, R1
	SRLD	$2, R3, R2
	XOR	R2, R1
	SRLD	$7, R3, R2
	XOR	R2, R1
	XOR	R1, R5
	SLLD	$63, R3, R1
	SLLD	$62, R3, R2
	XOR	R2, R1
	SLLD	$57, R3, R2
	XOR	R2, R1
	XOR	R1, R4

	SRLD	$1, R4, R1
	XOR	R4, R1
	SRLD	$2, R4, R2
	XOR	R2, R1
	SRLD	$7, R4, R2
	XOR	R2, R1
	XOR	R1, R19
	SLLD	$63, R4, R1
	SLLD	$62, R4, R2
	XOR	R2, R1
	SLLD	$57, R4, R2
	XOR	R2, R1
	XOR	R1, R5

	MOVD	R19, R12
	MOVD	R5, R13
	ADD	$16, R10
	SUB	$1, R11
	JMP	ghashloop

ghashdone:
	MOVD	R12, (R9)
	MOVD	R13, 8(R9)
	RET

// func gcmCtrBlocks(nr int, xk *uint32, dst, src *byte, n int, ctr *[2]uint64)
//
// Encrypts n counter blocks and XORs them into src, writing dst, then
// stores the next counter. Only the low 32 bits of the counter count,
// as GCM requires. The first round key is applied in the integer
// registers; the rest stay in %d8 onwards for the whole call, which
// for AES-256 is every double register: the state alternates between
// %d0:%d2 and %d4:%d6. dst and src are 8-aligned.
TEXT ·gcmCtrBlocks(SB), NOSPLIT|NOFRAME, $0-48
	MOVD	nr+0(FP), R8
	MOVD	xk+8(FP), R9
	MOVD	dst+16(FP), R10
	MOVD	src+24(FP), R11
	MOVD	n+32(FP), R12
	MOVD	ctr+40(FP), R13
	MOVD	(R13), R16
	MOVD	8(R13), R17
	MOVD	(R9), R18
	MOVD	8(R9), R19
	CMP	$10, R8
	BED	ctr128
	CMP	$12, R8
	BED	ctr192
	FMOVD	16(R9), D8
	FMOVD	24(R9), D10
	FMOVD	32(R9), D12
	FMOVD	40(R9), D14
	FMOVD	48(R9), D16
	FMOVD	56(R9), D18
	FMOVD	64(R9), D20
	FMOVD	72(R9), D22
	FMOVD	80(R9), D24
	FMOVD	88(R9), D26
	FMOVD	96(R9), D28
	FMOVD	104(R9), D30
	FMOVD	112(R9), D32
	FMOVD	120(R9), D34
	FMOVD	128(R9), D36
	FMOVD	136(R9), D38
	FMOVD	144(R9), D40
	FMOVD	152(R9), D42
	FMOVD	160(R9), D44
	FMOVD	168(R9), D46
	FMOVD	176(R9), D48
	FMOVD	184(R9), D50
	FMOVD	192(R9), D52
	FMOVD	200(R9), D54
	FMOVD	208(R9), D56
	FMOVD	216(R9), D58
	FMOVD	224(R9), D60
	FMOVD	232(R9), D62

ctrloop256:
	BRZ	R12, ctrdone
	XOR	R16, R18, R1
	XOR	R17, R19, R2
	MOVXTOD	R1, D0
	MOVXTOD	R2, D2
	AESEROUND01	D8, D0, D2, D4
	AESEROUND23	D10, D0, D2, D6
	AESEROUND01	D12, D4, D6, D0
	AESEROUND23	D14, D4, D6, D2
	AESEROUND01	D16, D0, D2, D4
	AESEROUND23	D18, D0, D2, D6
	AESEROUND01	D20, D4, D6, D0
	AESEROUND23	D22, D4, D6, D2
	AESEROUND01	D24, D0, D2, D4
	AESEROUND23	D26, D0, D2, D6
	AESEROUND01	D28, D4, D6, D0
	AESEROUND23	D30, D4, D6, D2
	AESEROUND01	D32, D0, D2, D4
	AESEROUND23	D34, D0, D2, D6
	AESEROUND01	D36, D4, D6, D0
	AESEROUND23	D38, D4, D6, D2
	AESEROUND01	D40, D0, D2, D4
	AESEROUND23	D42, D0, D2, D6
	AESEROUND01	D44, D4, D6, D0
	AESEROUND23	D46, D4, D6, D2
	AESEROUND01	D48, D0, D2, D4
	AESEROUND23	D50, D0, D2, D6
	AESEROUND01	D52, D4, D6, D0
	AESEROUND23	D54, D4, D6, D2
	AESEROUND01	D56, D0, D2, D4
	AESEROUND23	D58, D0, D2, D6
	AESEROUND01L	D60, D4, D6, D0
	AESEROUND23L	D62, D4, D6, D2
	MOVDTOX	D0, R1
	MOVDTOX	D2, R2
	MOVD	(R11), R3
	MOVD	8(R11), R4
	XOR	R3, R1
	XOR	R4, R2
	MOVD	R1, (R10)
	MOVD	R2, 8(R10)
	ADD	$1, R17, R3
	SLLD	$32, R3, R3
	SRLD	$32, R3, R3
	SRLD	$32, R17, R17
	SLLD	$32, R17, R17
	OR	R3, R17
	ADD	$16, R10
	ADD	$16, R11
	SUB	$1, R12
	JMP	ctrloop256

